"""
dossier_sections.py  (v25)
==========================
Dossier separation: what the papers SAY, what a MODEL computed, and what an AI PROPOSED are three different kinds of
statement and are never mixed. Every dossier gets three labelled sections:

    A. PUBLISHED EVIDENCE        verified findings from the papers read: each with its verbatim quote, the source, the
                                 reading confidence (full text / abstract only, second reader) and the calibrated verdict
    B. SIMULATION RESULTS        in-silico results (virtual lab hypothesis checks, model runs, sensitivity, validation):
                                 each with the model, its version, its assumptions and limits - consistency with a model,
                                 never evidence
    C. AI HYPOTHESES             ideas generated by the AI or derived from the evidence: untested by definition,
                                 each with how it could be falsified

    sections(dossier) -> {'published_evidence': [...], 'simulation_results': [...], 'ai_hypotheses': [...]}
    markdown(dossier) -> the three sections, to put at the top of the report
    label_report(text) -> tags the report's own hypothesis / virtual-lab headings with their section
"""
from __future__ import annotations

import re
from typing import Any, Dict, List

SECTIONS_VERSION = "1.0"
LABEL = {"published_evidence": "A. Published evidence (from the papers read)",
         "simulation_results": "B. Simulation results (in silico - a model, not evidence)",
         "ai_hypotheses": "C. AI hypotheses (untested - not evidence)"}


def sections(d: Dict[str, Any]) -> Dict[str, List[Dict[str, Any]]]:
    pub = []
    for r in (d.get("evidence_matrix") or {}).get("rows") or []:
        for f in r.get("findings") or []:
            if f.get("answers_question") is False:
                continue
            pub.append({"ref": r.get("ref"), "study": r.get("study") or r.get("title"), "design": r.get("evidence_type_label"),
                        "endpoint": f.get("endpoint"), "direction": f.get("direction"), "quote": f.get("quote"),
                        "link": r.get("link"), "text_basis": r.get("text_basis"),
                        "reading_confidence": r.get("extraction_confidence"), "second_reader": r.get("second_reader")})
    sim = []
    for h in d.get("virtual_lab") or (d.get("executive_synthesis") or {}).get("virtual_lab") or []:
        sim.append({"kind": "hypothesis check", "hypothesis": h.get("hypothesis") or h.get("statement"),
                    "verdict": h.get("verdict"), "tools": h.get("tools") or h.get("checks"), "basis": "in silico"})
    for t in d.get("hypothesis_tests") or []:
        sim.append({"kind": "hypothesis check", "hypothesis": t.get("statement"),
                    "verdict": f"laboratory: {t.get('verdict_plain') or t.get('verdict')}", "tools": [t.get("how")],
                    "basis": "in silico"})
    for v in d.get("claim_verification") or (d.get("executive_synthesis") or {}).get("claim_verification") or []:
        sim.append({"kind": "hypothesis check", "hypothesis": v.get("claim"),
                    "verdict": f"simulator: {v.get('verdict')}", "tools": [t.get("test") for t in v.get("tests") or []],
                    "basis": "in silico"})
    for e in d.get("experiments") or []:
        sim.append({"kind": "model run", "model": e.get("model"), "model_version": e.get("model_version"),
                    "result": e.get("expected") or e.get("threshold"), "assumptions": e.get("assumptions"),
                    "limits": e.get("limits"), "basis": "in silico"})
    hyp = []
    for h in d.get("hypotheses") or []:
        hyp.append({"statement": h.get("statement") or h.get("hypothesis"), "kind": h.get("kind") or h.get("hypothesis_kind"),
                    "falsified_if": h.get("falsification_conditions") or h.get("falsified_if"),
                    "next_experiment": h.get("next_experiment"), "source": h.get("source") or "AI / evidence-derived"})
    return {"published_evidence": pub, "simulation_results": sim, "ai_hypotheses": hyp}


def _cell(s: Any, n: int = 140) -> str:
    s = re.sub(r"\s+", " ", str(s or "")).replace("|", "/")
    return s if len(s) <= n else s[:n - 1] + "…"


def markdown(d: Dict[str, Any]) -> str:
    S = sections(d)
    v = d.get("calibrated_verdict") or {}
    L = ["## How to read this dossier", "",
         "It has three kinds of content, kept apart: **A** what the papers report (evidence), **B** what a computer model "
         "computed (in silico - not evidence), **C** what the AI proposes (hypotheses - untested).", "",
         f"### {LABEL['published_evidence']}", ""]
    if v:
        L.append(f"Verdict: **{v.get('label')}**" + (f" - direction: {v.get('direction')}" if v.get("direction") not in (None, "unclear") else ""))
        L.append("")
    if S["published_evidence"]:
        L += ["| ref | design | endpoint | direction | verbatim quote | read from | confidence |", "|---|---|---|---|---|---|---|"]
        for x in S["published_evidence"][:60]:
            conf = (x.get("reading_confidence") or "") + (", 2nd reader agrees" if x.get("second_reader") == "agree" else
                                                          ", 2nd reader disagrees" if x.get("second_reader") == "disagree" else "")
            ref = f"[{x['ref']}]({x['link']})" if x.get("link") else x["ref"]
            L.append(f"| {ref} | {_cell(x.get('design'), 30)} | {_cell(x.get('endpoint'), 30)} | {x.get('direction') or ''} | "
                     f"“{_cell(x.get('quote'), 160)}” | {x.get('text_basis') or ''} | {conf} |")
    else:
        L.append("No verified finding answers the question.")
    L += ["", f"### {LABEL['simulation_results']}", ""]
    if S["simulation_results"]:
        for x in S["simulation_results"]:
            if x["kind"] == "hypothesis check":
                L.append(f"- Hypothesis check: {_cell(x.get('hypothesis'), 160)} -> **{x.get('verdict')}**")
            else:
                L.append(f"- Model {x.get('model')} (version {x.get('model_version')}): {_cell(x.get('result'), 200)}"
                         + (f" - limits: {_cell('; '.join(x.get('limits') or []), 160)}" if x.get("limits") else ""))
    else:
        L.append("No simulation was run for this question.")
    L += ["", f"### {LABEL['ai_hypotheses']}", ""]
    if S["ai_hypotheses"]:
        for i, x in enumerate(S["ai_hypotheses"], 1):
            fal = x.get("falsified_if")
            fal = "; ".join(fal) if isinstance(fal, list) else fal
            L.append(f"{i}. {_cell(x.get('statement'), 220)}" + (f" - *falsified if:* {_cell(fal, 160)}" if fal else ""))
    else:
        L.append("No hypothesis was generated.")
    L.append("")
    return "\n".join(L) + "\n"


def label_report(text: str) -> str:
    """Tag the report's own headings so a reader landing mid-report still sees which kind of content it is."""
    t = text or ""
    t = re.sub(r"(?m)^(#{2,3})\s+((?:Testable |Falsifiable |Evidence-derived )?Hypothes[ie]s\b.*)$",
               lambda m: f"{m.group(1)} {m.group(2)} — [C. AI hypotheses: untested, not evidence]" if "[C." not in m.group(2) else m.group(0), t)
    t = re.sub(r"(?m)^(#{2,3})\s+((?:Virtual lab|In[- ]silico|Simulation).*)$",
               lambda m: f"{m.group(1)} {m.group(2)} — [B. Simulation: a model, not evidence]" if "[B." not in m.group(2) else m.group(0), t)
    return t
